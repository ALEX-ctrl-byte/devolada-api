SELECT DATABASE() AS base_seleccionada, VERSION() AS version_mysql;
SHOW TABLES;
SHOW CREATE TABLE usuarios;
SHOW CREATE TABLE otp;
SHOW CREATE TABLE sesiones;
SHOW CREATE TABLE conductores;
SHOW CREATE TABLE empresas;
SHOW CREATE TABLE viajes;
SHOW CREATE TABLE billeteras;
